'use strict';
const {test} = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const generator = require('../scripts/create_testnet_settings');

test('testnet settings are generated from the maintained template with strict network isolation', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'nito-testnet-settings-'));
  t.after(() => fs.rm(directory, {recursive: true, force: true}));
  const output = path.join(directory, 'settings.testnet.json');
  const marker = path.join(directory, '.nito-instance');
  const generated = generator.testnetSettings(generator.readTemplate());
  generator.writeSettings(output, generated);
  const parsed = JSON.parse(await fs.readFile(output, 'utf8'));
  assert.equal(parsed.webserver.port, 3002);
  assert.equal(parsed.webserver.bind, '127.0.0.1');
  assert.equal(parsed.wallet.host, '127.0.0.1');
  assert.equal(parsed.wallet.port, 8845);
  assert.equal(parsed.dbsettings.database, 'nito_explorer_testnet');
  assert.equal(parsed.dbsettings.address, '127.0.0.1');
  assert.equal(parsed.dbsettings.port, 27018);
  assert.equal(parsed.dbsettings.auth_source, 'nito_explorer_testnet');
  assert.deepEqual(parsed.network.require_indexes, ['txindex', 'coinstatsindex']);
  assert.equal(parsed.network.expected_chain, 'test');
  assert.equal(parsed.network.expected_genesis, generator.TESTNET_GENESIS);
  assert.equal(parsed.network.private_activation_height, 0);
  assert.equal(parsed.network.require_private_active, true);
  assert.equal(parsed.network.process_suffix, 'testnet');
  assert.equal(parsed.network.web_instances, 1);
  assert.equal(parsed.network.supervise_indexer, true);
  assert.equal(parsed.network.allow_market_data, false);
  assert.equal(parsed.network.robots_noindex, true);
  assert.equal(parsed.markets_page.enabled, false);
  assert.ok(Object.values(parsed.markets_page.exchanges).every(exchange => exchange.enabled === false));
  assert.equal(parsed.shared_pages.logo, generator.TESTNET_LOGO);
  assert.equal(parsed.shared_pages.favicons.favicon32, generator.TESTNET_LOGO.slice(1));
  assert.equal(parsed.shared_pages.favicons.favicon128, '');
  assert.equal(parsed.shared_pages.page_header.home_link_logo, generator.TESTNET_LOGO);
  assert.equal(parsed.shared_pages.page_header.page_title_image.image_path, generator.TESTNET_LOGO);
  assert.equal(parsed.shared_pages.page_header.bgcolor, 'success');
  assert.equal(parsed.shared_pages.page_footer.bgcolor, 'success');
  assert.equal(parsed.shared_pages.page_header.panels.logo_panel.enabled, false);
  assert.equal(parsed.api_page.show_logo, false);
  assert.throws(() => generator.writeSettings(output, generated), /EEXIST/);
  generator.writeInstanceMarker(marker);
  assert.equal(await fs.readFile(marker, 'utf8'), 'testnet\n');
  generator.writeInstanceMarker(marker);
  await fs.writeFile(marker, 'mainnet\n');
  assert.throws(() => generator.validateInstanceMarker(marker), /does not identify testnet/);
});

test('generator CLI arguments reject ambiguous input', () => {
  assert.equal(generator.argumentsFrom([]).output, path.resolve('settings.testnet.json'));
  assert.equal(generator.argumentsFrom([]).instanceMarker, path.resolve('.nito-instance'));
  assert.equal(generator.argumentsFrom(['--output', 'custom.json']).output, path.resolve('custom.json'));
  assert.throws(() => generator.argumentsFrom(['--output']), /requires/);
  assert.throws(() => generator.argumentsFrom(['custom.json']), /Unknown option/);
});
